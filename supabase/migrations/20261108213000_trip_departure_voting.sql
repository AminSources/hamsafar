-- Departure time voting for trips.
-- Applied directly to the production Supabase project on 2026-11-08.

create table if not exists public.trip_departure_options (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint trip_departure_options_valid_range check (ends_at > starts_at),
  constraint trip_departure_options_trip_id_id_unique unique (trip_id, id)
);

create table if not exists public.trip_departure_votes (
  trip_id bigint not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  option_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (trip_id, user_id),
  constraint trip_departure_votes_option_fk foreign key (trip_id, option_id)
    references public.trip_departure_options(trip_id, id) on delete cascade
);

create index if not exists trip_departure_options_trip_idx on public.trip_departure_options(trip_id, starts_at);
create index if not exists trip_departure_votes_option_idx on public.trip_departure_votes(trip_id, option_id);

alter table public.trip_departure_options enable row level security;
alter table public.trip_departure_votes enable row level security;

create policy "Trip members can read departure options"
on public.trip_departure_options for select to authenticated
using (exists (select 1 from public.trips t where t.id=trip_id and (
  t.created_by=(select auth.uid()) or exists (
    select 1 from public.trip_members tm where tm.trip_id=t.id
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted'
  )
)));

create policy "Trip creators manage departure options"
on public.trip_departure_options for all to authenticated
using (exists (select 1 from public.trips t where t.id=trip_id and t.created_by=(select auth.uid())))
with check (exists (select 1 from public.trips t where t.id=trip_id and t.created_by=(select auth.uid())));

create policy "Trip members read departure votes"
on public.trip_departure_votes for select to authenticated
using (exists (select 1 from public.trips t where t.id=trip_id and (
  t.created_by=(select auth.uid()) or exists (
    select 1 from public.trip_members tm where tm.trip_id=t.id
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted'
  )
)));

create policy "Members cast own departure vote"
on public.trip_departure_votes for insert to authenticated
with check (
  user_id=(select auth.uid())
  and exists (select 1 from public.trips t where t.id=trip_id
    and t.schedule_type='voting' and t.status='preparing'
    and exists (select 1 from public.trip_members tm where tm.trip_id=t.id
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted'))
  and exists (select 1 from public.trip_departure_options o where o.id=option_id and o.trip_id=trip_id)
);

create policy "Members update own departure vote"
on public.trip_departure_votes for update to authenticated
using (
  user_id=(select auth.uid())
  and exists (select 1 from public.trips t join public.trip_members tm on tm.trip_id=t.id
    where t.id=trip_id and t.schedule_type='voting' and t.status='preparing'
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted')
)
with check (
  user_id=(select auth.uid())
  and exists (select 1 from public.trips t join public.trip_members tm on tm.trip_id=t.id
    where t.id=trip_id and t.schedule_type='voting' and t.status='preparing'
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted')
  and exists (select 1 from public.trip_departure_options o where o.id=option_id and o.trip_id=trip_id)
);

grant select on public.trip_departure_options, public.trip_departure_votes to authenticated;
grant insert, update, delete on public.trip_departure_options to authenticated;
grant insert, update on public.trip_departure_votes to authenticated;
grant usage, select on sequence public.trip_departure_options_id_seq to authenticated;

create or replace function public.replace_trip_departure_options(p_trip_id bigint, p_options jsonb)
returns void language plpgsql security invoker set search_path = ''
as $$
declare v_user_id uuid := (select auth.uid());
begin
  if v_user_id is null then raise exception 'not_authenticated'; end if;
  if not exists (select 1 from public.trips t where t.id=p_trip_id and t.created_by=v_user_id) then
    raise exception 'trip_not_found_or_forbidden';
  end if;
  if not exists (select 1 from public.trips t where t.id=p_trip_id and t.schedule_type='voting') then
    delete from public.trip_departure_options where trip_id=p_trip_id;
    return;
  end if;
  if jsonb_typeof(coalesce(p_options,'[]'::jsonb)) <> 'array'
     or jsonb_array_length(coalesce(p_options,'[]'::jsonb)) < 2 then
    raise exception 'at_least_two_departure_options_required';
  end if;
  if jsonb_array_length(p_options)>10 then raise exception 'too_many_departure_options'; end if;
  if exists (select 1 from jsonb_array_elements(p_options) x
    where nullif(x->>'starts_at','') is null or nullif(x->>'ends_at','') is null
      or (x->>'ends_at')::timestamptz <= (x->>'starts_at')::timestamptz) then
    raise exception 'invalid_departure_option_range';
  end if;
  delete from public.trip_departure_options where trip_id=p_trip_id;
  insert into public.trip_departure_options(trip_id,starts_at,ends_at)
  select p_trip_id,(x->>'starts_at')::timestamptz,(x->>'ends_at')::timestamptz
  from jsonb_array_elements(p_options) x;
end;
$$;

create or replace function public.get_my_departure_polls()
returns table(trip_id bigint,trip_name text,location text,options jsonb,total_voters bigint,my_option_id bigint)
language sql stable security invoker set search_path = ''
as $$
  select t.id,t.name,t.location,
    coalesce((select jsonb_agg(jsonb_build_object(
      'id',o.id,'starts_at',o.starts_at,'ends_at',o.ends_at,
      'vote_count',(select count(*) from public.trip_departure_votes v where v.trip_id=t.id and v.option_id=o.id)
    ) order by o.starts_at) from public.trip_departure_options o where o.trip_id=t.id),'[]'::jsonb),
    (select count(*) from public.trip_departure_votes v where v.trip_id=t.id),
    (select v.option_id from public.trip_departure_votes v where v.trip_id=t.id and v.user_id=(select auth.uid()))
  from public.trips t
  where t.schedule_type='voting' and t.status='preparing'
    and exists (select 1 from public.trip_members tm where tm.trip_id=t.id
      and tm.user_id=(select auth.uid()) and tm.member_status='accepted')
    and exists (select 1 from public.trip_departure_options o where o.trip_id=t.id)
  order by t.departure_at;
$$;

create or replace function public.cast_departure_vote(p_trip_id bigint,p_option_id bigint)
returns void language plpgsql security invoker set search_path = ''
as $$
declare v_user_id uuid := (select auth.uid());
begin
  if v_user_id is null then raise exception 'not_authenticated'; end if;
  if not exists (select 1 from public.trips t join public.trip_members tm on tm.trip_id=t.id
    where t.id=p_trip_id and t.schedule_type='voting' and t.status='preparing'
      and tm.user_id=v_user_id and tm.member_status='accepted') then
    raise exception 'departure_poll_not_available';
  end if;
  if not exists (select 1 from public.trip_departure_options o where o.id=p_option_id and o.trip_id=p_trip_id) then
    raise exception 'invalid_departure_option';
  end if;
  insert into public.trip_departure_votes(trip_id,user_id,option_id)
  values(p_trip_id,v_user_id,p_option_id)
  on conflict(trip_id,user_id) do update set option_id=excluded.option_id,updated_at=now();
end;
$$;

grant execute on function public.replace_trip_departure_options(bigint,jsonb) to authenticated;
grant execute on function public.get_my_departure_polls() to authenticated;
grant execute on function public.cast_departure_vote(bigint,bigint) to authenticated;
